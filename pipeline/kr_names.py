def from_kind(timeout=30):
    """KIND 상장법인 목록 → {종목코드: 회사명}. 실패하면 빈 dict."""
    url = "https://kind.krx.co.kr/corpgeneral/corpList.do"
    try:
        r = requests.get(url, params={"method": "download", "searchType": "13"}, headers=UA, timeout=timeout)
        r.raise_for_status()
        text = r.content.decode("cp949", errors="replace")
        df = pd.read_html(io.StringIO(text), header=0)[0]
        name_col = next(c for c in df.columns if "회사명" in str(c))
        code_col = next(c for c in df.columns if "종목코드" in str(c))
        out = {}
        for _, row in df.iterrows():
            code = str(row[code_col]).strip().upper()
            if code.isdigit():
                code = code.zfill(6)
            name = str(row[name_col]).strip()
            if len(code) == 6 and name and name != "nan":
                out[code] = name
        return out if len(out) > 500 else {}
    except Exception:  # noqa: BLE001
        return {}


def lookup(log=print):
    """{코드: 한글명}. KIND가 되면 KIND 이름이 우선, 나머지는 고정 목록."""
    kind = from_kind()
    log(f"[names] KIND 상장법인 목록 {len(kind)}개" if kind else "[names] KIND 목록을 받지 못해 고정 목록만 사용")
    return {**KR_NAMES, **kind}
